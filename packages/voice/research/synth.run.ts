import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { ENROLLED, ENROLMENT, LINES, SPEAKER_OF } from "./lines.js";
import { VOICE_OF, render, rng, type Mix } from "./synth.js";

// Builds the synthetic labelled set with macOS voices into --out (kept out of git) and writes its manifest with every file hash.
const arg = (k: string, d: string) => { const i = process.argv.indexOf(`--${k}`); return i > 0 ? process.argv[i + 1] ?? d : d; };
const out = arg("out", ".hey-pisgah/r1/synth");
const manifest = arg("manifest", "packages/voice/research/synthetic-set.json");
mkdirSync(out, { recursive: true });

type Clip = { id: string; line: string | null; set: "enrolment" | "tuning" | "final"; file: string; sha256: string; duration_ms: number; snr_db: number; parts: Mix[] };
const clips: Clip[] = [];
const keep = (id: string, line: string | null, set: Clip["set"], parts: Mix[], snr: number) => {
  const r = render(parts, snr, id);
  const file = `${id}.wav`;
  writeFileSync(join(out, file), r.wav);
  clips.push({ id, line, set, file, sha256: r.sha256, duration_ms: r.duration_ms, snr_db: Math.round(snr * 10) / 10, parts });
  process.stderr.write(`${id} ${r.duration_ms} ms\n`);
};

// Enrolment is read close to the laptop in a quiet room, as at onboarding.
for (const p of ENROLLED) ENROLMENT.forEach((words, i) => keep(`E${i + 1}-${p}`, null, "enrolment", [{ voice: p, at_ms: 0, gain: 0.85, far: false, rate: 180 + i * 8, words }], 40));

// Tuning-only variants (T01v1 and so on) give the local model's threshold more than 24 points; they never reach the final set.
const variants = Number(arg("variants", "0"));
const jobs = [...LINES.map((l) => ({ l, id: l.id })), ...LINES.filter((l) => l.set === "tuning").flatMap((l) => Array.from({ length: variants }, (_, k) => ({ l, id: `${l.id}v${k + 1}` })))];
for (const { l, id } of jobs) {
  const r = rng(id);
  const owner = l.who === "S";
  const main: Mix = { voice: l.who, at_ms: 0, gain: owner ? 0.8 + r() * 0.1 : 0.45 + r() * 0.2, far: !owner, rate: Math.round(owner ? 175 + r() * 25 : 165 + r() * 45), words: l.words };
  const parts: Mix[] = [main];
  if (l.overlap) {
    const o = l.overlap.who;
    parts.push({ voice: o, at_ms: Math.round(800 + r() * 400), gain: o === "S" ? 0.7 : 0.45 + r() * 0.15, far: o !== "S", rate: Math.round(170 + r() * 30), words: l.overlap.words });
  }
  keep(id, l.id, l.set, parts, id !== l.id ? 12 + r() * 12 : l.noisy ? 12 + r() * 6 : 35 + r() * 10);
}

writeFileSync(manifest, `${JSON.stringify({
  set: "synthetic-say-v1", rate_hz: 24000, voices: VOICE_OF, speaker_of: SPEAKER_OF,
  note: "Audio is regenerated by synth.run.ts and kept out of git; each file is checked by its hash before scoring.",
  clips: clips.map(({ parts, ...c }) => ({ ...c, parts: parts.map(({ words: _w, ...p }) => p) }))
}, null, 1)}\n`);
process.stderr.write(`${clips.length} clips written\n`);
